import requests

# Load the API key from a local text file.
# api_key.txt should be in the current working directory.
with open("api_key.txt", "r", encoding="utf-8") as file:
    api_key = file.read().strip()  # Read the key and remove whitespace.

# Set the API endpoint.
url = "https://aigc-api.hkust-gz.edu.cn/api/v2/chat/completions"

# Prepare the HTTP request headers.
headers = {
    "Authorization": f"Bearer {api_key}",  # Use the API key loaded from the file.
    "Content-Type": "application/json"
}

# Prepare the request body.
payload = {
    "model": "DeepSeek-V4-Pro",
    "messages": [
        {"role": "system", "content": "你是一个有用的助手"},
        {"role": "user", "content": "请介绍一下自己"}
    ],
}

# Send the request to the API server.
response = requests.post(url, headers=headers, json=payload)

# Check whether the HTTP request was successful.
print("HTTP Status:", response.status_code)
print("Error Response:", response.text)
response.raise_for_status()

# Convert the JSON response to a Python dictionary.
result = response.json()

# Print the response generated by the model.
print(result["choices"][0]["message"]["content"])