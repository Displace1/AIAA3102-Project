import argparse
import json
import random
from pathlib import Path

from PIL import Image, ImageDraw


CLASS_NAMES = ("dark", "light")
SPLIT_SIZES = {
    "train": 12,
    "validation": 4,
    "test": 4,
}


def create_synthetic_image_dataset(output_directory, overwrite=False):
    """Create a tiny labeled RGB dataset for end-to-end smoke tests."""

    output_directory = Path(output_directory).expanduser().resolve()
    if output_directory.exists() and any(output_directory.iterdir()):
        if not overwrite:
            raise FileExistsError(
                "Synthetic image output directory is not empty: "
                f"{output_directory}. Use --force to overwrite generated files."
            )
    output_directory.mkdir(parents=True, exist_ok=True)

    random_generator = random.Random(42)
    for split_name, samples_per_class in SPLIT_SIZES.items():
        for class_name in CLASS_NAMES:
            class_directory = output_directory / split_name / class_name
            class_directory.mkdir(parents=True, exist_ok=True)
            base_value = 30 if class_name == "dark" else 225
            for index in range(samples_per_class):
                jitter = random_generator.randint(-15, 15)
                value = max(0, min(255, base_value + jitter))
                image = Image.new("RGB", (48, 48), (value, value, value))
                draw = ImageDraw.Draw(image)
                accent = 80 if class_name == "dark" else 175
                offset = 4 + index % 12
                draw.rectangle(
                    (offset, offset, 47 - offset, 47 - offset),
                    outline=(accent, accent, accent),
                    width=2,
                )
                image.save(class_directory / f"{class_name}_{index:03d}.png")

    return output_directory


def write_smoke_config(config_path, dataset_directory, overwrite=False):
    config_path = Path(config_path).expanduser().resolve()
    dataset_directory = Path(dataset_directory).expanduser().resolve()
    if config_path.exists() and not overwrite:
        raise FileExistsError(
            f"Smoke configuration already exists: {config_path}. "
            "Use --force to overwrite it."
        )

    config = {
        "run_type": "development_run",
        "task": {
            "name": "synthetic_image_smoke",
            "metric": "accuracy",
        },
        "data": {
            "format": "image_directory_split",
            "train_directory": str(dataset_directory / "train"),
            "validation_directory": str(dataset_directory / "validation"),
            "test_directory": str(dataset_directory / "test"),
        },
        "execution": {
            "random_seed": 42,
            "evaluate_test": False,
            "planner_mode": "deterministic",
            "initial_deterministic_experiments": 1,
            "max_experiments": 1,
            "max_runtime_minutes": 20,
            "no_improvement_patience": 2,
            "minimum_improvement": 0.001,
            "maximum_planner_errors": 2,
            "maximum_same_experiment_errors": 2,
            "experiment_timeout_seconds": 600,
            "maximum_memory_mb": 4096,
            "maximum_cpu_threads": 2,
            "resource_poll_interval_seconds": 0.1,
        },
    }
    config_path.parent.mkdir(parents=True, exist_ok=True)
    temporary_path = config_path.with_suffix(config_path.suffix + ".tmp")
    try:
        with temporary_path.open("w", encoding="utf-8") as file:
            json.dump(config, file, ensure_ascii=False, indent=2)
        temporary_path.replace(config_path)
    finally:
        if temporary_path.exists():
            temporary_path.unlink()
    return config_path


def main():
    project_root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(
        description="Create a deterministic image-classification smoke dataset."
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=project_root / "smoke_data" / "synthetic_image",
    )
    parser.add_argument(
        "--config-output",
        type=Path,
        default=project_root / "configs" / "image_smoke.json",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite files generated by an earlier invocation.",
    )
    args = parser.parse_args()

    dataset_directory = create_synthetic_image_dataset(
        args.output_dir,
        overwrite=args.force,
    )
    config_path = write_smoke_config(
        args.config_output,
        dataset_directory,
        overwrite=args.force,
    )
    print(f"Synthetic dataset: {dataset_directory}")
    print(f"Task configuration: {config_path}")
    print("Next: python .\\main.py --config .\\configs\\image_smoke.json")


if __name__ == "__main__":
    main()
